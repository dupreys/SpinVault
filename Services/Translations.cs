    public static string ToEnglish(string pt)
    {
        if (Map.TryGetValue(pt, out var direct))
            return Adjust(pt, direct);

        // Separa o que vem antes da primeira letra/número (ícones, espaços, aspas) e os espaços do fim.
        var start = 0;
        while (start < pt.Length && !char.IsLetterOrDigit(pt[start]) && pt[start] != '{')
            start++;
        var end = pt.Length;
        while (end > start && char.IsWhiteSpace(pt[end - 1]))
            end--;
        if (start >= end)
            return pt;

        var core = pt[start..end];
        return Map.TryGetValue(core, out var found)
            ? pt[..start] + Adjust(core, found) + pt[end..]
            : pt;
    }

    /// <summary>Textos em CAIXA ALTA (cabeçalhos) continuam em caixa alta na tradução.</summary>
    private static string Adjust(string source, string translation)
    {
        var letters = source.Count(char.IsLetter);
        return letters >= 2 && source.Where(char.IsLetter).All(char.IsUpper)
            ? translation.ToUpperInvariant()
            : translation;
    }
